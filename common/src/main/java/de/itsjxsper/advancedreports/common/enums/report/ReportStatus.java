/**
 * Enum representing the status of a report.
 */
public enum ReportStatus {
    /**
     * The report is pending review.
     */
    PENDING,
    /**
     * The report has been approved.
     */
    APPROVED,
    /**
     * The report has been rejected.
     */
    REJECTED
}
